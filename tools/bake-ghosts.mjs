// Bake the *watchable* part of the leaderboard: the top N runs of each track.
//
// Only the head of the board needs a real run behind it (so the world record and
// the fastest few can be watched). The rest of the field is generated from a
// formula in js/leaderboard.js and is not watchable. That keeps this fast and the
// output tiny.
//
// A ghost is a run of the real physics driven by a deterministic button policy
// (see js/ghostrun.js), so its replay is re-simulated from its id on demand.
//
// Run:  node tools/bake-ghosts.mjs
import { writeFileSync } from 'node:fs';
import { Track } from '../js/track.js';
import { Car } from '../js/car.js';
import { trackOpts, TRACK_COUNT } from '../js/tracks.js';
import { ghostPolicy, ghostName } from '../js/ghostrun.js';

const TOP = 10;      // watchable runs per track
const SCAN = 1000;   // ids to try; more ids finds a faster world record
const DT = 1 / 120;

function simulate(track, id) {
  const car = new Car();
  car.reset(track);
  const policy = ghostPolicy(id);
  let i = 0;
  while (car.alive && i++ < 200000) car.step(DT, policy(car));
  return car.finished ? car.time : null;
}

const out = {};
for (let n = 1; n <= TRACK_COUNT; n++) {
  const track = new Track(n, trackOpts(n));
  const found = [];
  for (let id = 0; id < SCAN; id++) {
    const time = simulate(track, id);
    if (time !== null) found.push([Number(time.toFixed(4)), id]);
  }
  found.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const top = found.slice(0, TOP);
  out[n] = top;
  console.log(`track ${String(n).padStart(2)}: WR ${top[0][0].toFixed(3)}s, top ${top.length} of ${found.length} finishers`);
}

const header = `// GENERATED by tools/bake-ghosts.mjs - do not edit by hand.
// The watchable head of each track's board: [time, ghostId, name], fastest first.
// A ghost's replay is re-simulated from its id on demand (js/ghostrun.js).
`;
const body = Object.entries(out)
  .map(([n, rows]) => `  ${n}: [${rows.map(([t, id]) => `[${t},${id},${JSON.stringify(ghostName(id))}]`).join(',')}],`)
  .join('\n');
writeFileSync(new URL('../js/ghostdata.js', import.meta.url),
  `${header}export const GHOSTS = {\n${body}\n};\n`);
console.log('wrote js/ghostdata.js');
