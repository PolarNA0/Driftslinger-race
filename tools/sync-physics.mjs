// Vendor the physics into the Edge Function.
//
// The verifier has to replay a run with the game's own physics, or it would
// disagree with the Godot build about what a run is worth. Deno cannot import
// across the function directory, so the modules are copied in. Copies drift, so
// this runs as a check in CI and as a step before deploying:
//
//   node tools/sync-physics.mjs          # copy
//   node tools/sync-physics.mjs --check  # fail if the copies are stale
//
// The imports are rewritten to flat paths because the function directory has no
// `physics/` subdirectory to resolve `./config.js` against - it resolves it to itself,
// which is what we want, but the rewrite keeps it explicit and lets the check
// compare like for like.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const DEST = join(ROOT, 'supabase', 'functions', '_shared', 'physics');

// Order matters only for readability; the imports are what link them.
const FILES = ['config.js', 'util.js', 'track.js', 'car.js', 'tracks.js'];

const BANNER = `// GENERATED by tools/sync-physics.mjs - do not edit by hand.
// Copied verbatim from physics/%s so the Edge Function replays runs with exactly
// the physics the game runs. Edit physics/%s and re-run the sync.
`;

const REL = 'supabase/functions/_shared/physics';
const check = process.argv.includes('--check');

await mkdir(DEST, { recursive: true });

let stale = 0;
for (const name of FILES) {
  const src = await readFile(join(ROOT, 'physics', name), 'utf8');
  const out = BANNER.replace(/%s/g, name) + src;

  const target = join(DEST, name);
  let current = null;
  try { current = await readFile(target, 'utf8'); } catch { /* not copied yet */ }

  if (check) {
    if (current !== out) {
      stale++;
      console.log(`stale: ${REL}/${name}`);
    }
    continue;
  }

  if (current !== out) {
    await writeFile(target, out);
    console.log(`wrote ${REL}/${name}`);
  }
}

if (check) {
  if (stale) {
    console.error(`\n${stale} vendored file(s) out of date. Run: node tools/sync-physics.mjs`);
    process.exit(1);
  }
  console.log('vendored physics is up to date');
} else {
  console.log('physics synced into the Edge Function');
}
